print("Hasil Penjumlahan: " + str(input_angka1 + input_angka2))
print("Hasil Pengurangan: " + str(input_angka1 - input_angka2))
print("Hasil Perkalian: " + str(input_angka1 * input_angka2))
print("Hasil Pembagian: " + str(input_angka1 / input_angka2))
