# Materi input, operasi hitung
# Studi Kasus: Kalkulator Sederhana
print("================================")
print("Program Kalkulator Sederhana")
print("================================")

# input
input_angka1 = int(input("Masukkan Angka Pertama: "))
input_angka2 = int(input("Masukkan Angka Kedua: "))

# proses
penjumlahan = input_angka1 + input_angka2
pengurangan = input_angka1 - input_angka2
perkalian = input_angka1 * input_angka2
pembagian = input_angka1 / input_angka2


print("================================")

# output
print("Hasil Penjumlahan: ", penjumlahan)
print("Hasil Pengurangan: ", pengurangan)
print("Hasil Perkalian: ", perkalian)
print("Hasil Pembagian: ", pembagian)


print("================================")
